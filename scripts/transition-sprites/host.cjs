// Electron host for the sprite generator: runs the page hidden, then writes the atlas and the
// generated index module into packages/ui.
const { app, BrowserWindow } = require('electron');
const path = require('node:path');
const fs = require('node:fs');

const ROOT = path.join(__dirname, '..', '..');
let done = false;
const finish = (code, msg) => {
  if (done) return;
  done = true;
  process.stdout.write(msg + '\n', () => process.exit(code));
};
app.on('window-all-closed', () => {});

app.whenReady().then(() => {
  const win = new BrowserWindow({ show: false, width: 800, height: 600, webPreferences: { offscreen: false, backgroundThrottling: false } });
  win.webContents.on('console-message', async (_e, _l, message) => {
    if (message !== '__DONE__') return;
    try {
      const atlas = await win.webContents.executeJavaScript('window.__atlas');
      const meta = await win.webContents.executeJavaScript('window.__meta');
      if (meta.failed.length) return finish(1, 'some frames failed to draw: ' + meta.failed.slice(0, 10).join(', '));
      const png = Buffer.from(atlas.split(',')[1], 'base64');
      const out = path.join(ROOT, 'packages/ui/src/assets/transition-sprites.webp');
      fs.writeFileSync(out, png);
      const ts = `// GENERATED by scripts/transition-sprites (npm run gl-transition-sprites). Do not edit.
// One strip of ${meta.frames} real frames per transition, ${meta.frameW}x${meta.frameH} each, rows in this order.

export const SPRITE_FRAMES = ${meta.frames};
/** The frame a resting chip shows (the middle of the transition). */
export const SPRITE_REST = ${meta.rest};
export const SPRITE_ROWS = ${meta.count};
export const SPRITE_ROW_INDEX: Record<string, number> = ${JSON.stringify(meta.rows, null, 2)};
/** Per transition, the strip frame that makes the best resting thumbnail. */
export const SPRITE_REST_INDEX: Record<string, number> = ${JSON.stringify(meta.rests, null, 2)};

export const spriteRow = (type: string): number | undefined => SPRITE_ROW_INDEX[type];
export const spriteRest = (type: string): number => SPRITE_REST_INDEX[type] ?? SPRITE_REST;
`;
      fs.writeFileSync(path.join(ROOT, 'packages/ui/src/panels/browsers/transitionSprites.generated.ts'), ts);
      finish(0, `SPRITES ${meta.count} transitions x ${meta.frames} frames, ${(png.length / 1024).toFixed(0)} kB -> packages/ui/src/assets/transition-sprites.webp`);
    } catch (e) {
      finish(1, 'failed to write sprites: ' + e);
    }
  });
  win.webContents.on('render-process-gone', (_e, d) => finish(1, 'RENDERER GONE ' + JSON.stringify(d)));
  win.loadFile(path.join(__dirname, 'index.html')).catch((e) => finish(1, 'loadFile threw: ' + e));
  setTimeout(() => finish(1, 'TIMEOUT'), 150000);
});
